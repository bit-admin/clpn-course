ADD("7.6", "code", WARN("做不变性检验的常见错误", r"""<ul>
<li><b>度量模型里同时固定了第一个载荷和因子方差。</b>两种定刻度的方法只能选一种。本课用“第 1 波因子方差 = 1”，所以每个载荷前都要写 <code>NA*</code> 放开 lavaan 默认的“第一个载荷 = 1”。</li>
<li><b>载荷相等了，却忘了放开第 2、3 波的因子方差</b>（或截距相等了，却没放开因子均值）。这会把本来不同的方差 / 均值硬设成相等，拟合变差，被误判为“不变性不成立”。</li>
<li><b>漏写同一道题跨波次的残差相关。</b>同一道题每次都带着自己的特点（措辞、个人对这句话的理解），这些特点跨波次相关。不写的话，构形模型就拟合不好。</li>
<li><b>MLR 下把两个 χ² 直接相减。</b>稳健卡方要做缩放校正，用 <code>lavTestLRT()</code>；ΔCFI 用 <code>cfi.robust</code>，不要混用普通 CFI 和稳健 CFI。</li></ul>"""))

