ADD("6.3", "math", r"""
<h3>完整例题：LASSO 怎样把小系数“压”成 0</h3>
<p>考虑最简单的情形：预测变量已经标准化，而且彼此不相关。这时 glmnet 的 LASSO 解有一个简单的公式，叫<b>软阈值</b>（soft-thresholding）：</p>
""" + MATH(r"\hat\beta_j^{\text{LASSO}}=\operatorname{sign}(\hat\beta_j^{\text{OLS}})\cdot\max\left(|\hat\beta_j^{\text{OLS}}|-\lambda,\;0\right)") + r"""
<p>假设普通回归得到 4 个系数：0.30、0.12、−0.05、0.02，取 λ = 0.08：</p>
""" + TABLE(["OLS 系数", "|b| − λ", "LASSO 系数", "发生了什么"], [
["0.30", "0.22", "0.22", "保留，但向 0 收缩了 0.08"], ["0.12", "0.04", "0.04", "保留，收缩后已经很小"],
["−0.05", "−0.03 → 取 0", "0", "被压成 0（从网络中删除）"], ["0.02", "−0.06 → 取 0", "0", "被压成 0"]]) + r"""
<p>可以看到 LASSO 的两个特点：①绝对值小于 λ 的系数直接变成 0，网络因此变得稀疏；②保留下来的系数也都向 0 收缩了同样的量，所以 LASSO 估计的边权<b>系统性偏小</b>。岭回归（ridge）则不同，它把每个系数按比例缩小，但不会让任何系数正好等于 0，所以无法用来“选边”。</p>
<p>真实数据中预测变量是相关的，公式不再这么简单，但直觉相同：λ 越大，门槛越高，留下的边越少。EBICglasso 则在一串 λ 中，按 EBIC（拟合好坏 + 对边数的惩罚，γ 越大惩罚越重）挑出一个。</p>
""")
ADD("6.3", "code", WARN("使用正则化时的常见错误", r"""<ul>
<li><b>直接比较正则化边权与普通回归系数的大小。</b>正则化估计系统性偏小，不能拿来和其他研究的未正则化系数直接比较。</li>
<li><b>用调参换结果。</b>先试 γ = 0、0.25、0.5，挑一个“边最多”或“结论最好看”的，这是研究者自由度的滥用。应在分析计划中事先写明 γ（通常为 0.5），其他取值只作为敏感性分析报告。</li>
<li><b>样本很大时仍然以为网络“很稀疏”。</b>N 越大，越弱的边也能通过门槛。课程数据（N = 800）的横断面网络在 γ = 0、0.25、0.5 下都是 28 条边，说明在大样本中 γ 的影响可能很小。</li></ul>"""))

