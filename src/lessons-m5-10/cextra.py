ADD("6.2", "math", r"""
<h3>完整例题：亲手算出“条件独立”</h3>
<p>三个变量：失眠（1）、疲劳（2）、注意力差（3）。假设相关为 r₁₂ = 0.6，r₁₃ = 0.6，r₂₃ = 0.36。疲劳和注意力差的相关 0.36 不算小，但它是直接关联，还是“都受失眠影响”带来的？</p>
<p>控制失眠后，疲劳与注意力差的偏相关为：</p>
""" + MATH(r"r_{23\cdot1}=\frac{r_{23}-r_{12}r_{13}}{\sqrt{(1-r_{12}^2)(1-r_{13}^2)}}=\frac{0.36-0.6\times0.6}{\sqrt{0.64\times0.64}}=\frac{0}{0.64}=0") + r"""
<p>分子正好为 0：0.36 完全可以由“失眠 → 疲劳”和“失眠 → 注意力差”两条路径解释（0.6 × 0.6 = 0.36）。在偏相关网络里，疲劳与注意力差之间<b>没有边</b>。这就是“条件独立”的含义。</p>
<p>再算控制注意力差后，失眠与疲劳的偏相关：分子 = 0.6 − 0.6 × 0.36 = 0.384，分母 = √(0.64 × (1 − 0.1296)) ≈ 0.746，偏相关 ≈ 0.51。它比原来的 0.6 小，但仍然明显，所以失眠—疲劳这条边保留。最终的网络是一条“疲劳—失眠—注意力差”的链，失眠位于中间。</p>
<p>与 R 对照：<code>R &lt;- matrix(c(1, .6, .6, .6, 1, .36, .6, .36, 1), 3); P &lt;- -cov2cor(solve(R)); diag(P) &lt;- 1; round(P, 3)</code>。加负号后对角线会变成 −1，所以要用 <code>diag(P) &lt;- 1</code> 改回 1（与本课 R 代码中 <code>diag(pc) &lt;- 1</code> 相同）。非对角线上会出现 0.514 和 0。</p>
""")
ADD("6.2", "code", WARN("计算偏相关时的常见错误", r"""<ul>
<li><b>忘了负号。</b>由精度矩阵算偏相关的公式是 ρ = −k<sub>ij</sub>/√(k<sub>ii</sub>k<sub>jj</sub>)。<code>cov2cor(solve(R))</code> 得到的非对角元素正负号是反的，要再乘以 −1。</li>
<li><b>变量太多而样本太少。</b>p 接近 N 时，相关矩阵接近奇异，<code>solve()</code> 会报 “system is computationally singular”，或者得到很不稳定的结果。6.3 课要用正则化，这是原因之一。</li>
<li><b>把 T1 总分和各题一起放进网络。</b>总分是各题之和，与各题完全线性相关，矩阵无法求逆。网络里只放同一层次的变量。</li></ul>"""))

