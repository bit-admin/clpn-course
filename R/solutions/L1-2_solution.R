# 练习答案 L1-2
#   1.2-A：6 位居民的孤独感题目得分 2, 4, 1, 3, 4, 4 —— 均值、中位数、方差、标准差 + 直方图（横轴 1–4）
#   1.2-C：T2 抑郁总分（dep1_t2–dep5_t2）的均值、中位数、标准差，以及 0 分的人所占比例
#   （1.2-B 是讨论题，要点见讲义；最后附几行注释）
source("R/_setup.R")
log_open("sol_L1-2_log.txt")

# ---- 1.2-A 手算后用 R 验算 ----
x <- c(2, 4, 1, 3, 4, 4)
# 第 1 步 均值：(2+4+1+3+4+4)/6 = 18/6 = 3
# 第 2 步 中位数：排序 1, 2, 3, 4, 4, 4，中间两个数是 3 和 4 → (3+4)/2 = 3.5
# 第 3 步 离均差：-1, 1, -2, 0, 1, 1 ；平方：1, 1, 4, 0, 1, 1 ；平方和 = 8
# 第 4 步 方差 = 8 / (6-1) = 1.6 ；标准差 = √1.6 ≈ 1.26
stopifnot(mean(x) == 3, median(x) == 3.5, abs(var(x) - 1.6) < 1e-9)
cat("1.2-A：均值 =", mean(x), " 中位数 =", median(x), " 方差 =", var(x), " 标准差 =", round(sd(x), 2), "\n")
print(table(factor(x, levels = 1:4)))        # 1 分 1 人、2 分 1 人、3 分 1 人、4 分 3 人
# 直方图：每个整数分数一根柱子（边界放在 0.5, 1.5, …, 4.5）
png_open("sol_L1-2_hist.png", 1200, 1000)
hist(x, breaks = seq(0.5, 4.5, 1), col = "grey", main = "6 位居民的孤独感题目得分", xlab = "得分（1–4）", ylab = "人数")
invisible(dev.off())
cat("左偏：均值 3 < 中位数 3.5；一半人选了最高分 4 → 天花板效应的迹象\n\n")

# ---- 1.2-C T2 抑郁总分 ----
dat <- read_course_data()
dep_sum_t2 <- rowSums(dat[, paste0(dep_items, "_t2")])
cat("1.2-C：T2 抑郁总分\n")
cat("均值 =", round(mean(dep_sum_t2), 2), " 中位数 =", median(dep_sum_t2),
    " 标准差 =", round(sd(dep_sum_t2), 2), "\n")
cat("0 分的比例 =", round(mean(dep_sum_t2 == 0), 3), "\n")   # 逻辑值的均值 = TRUE 的比例
# 均值（约 3.78）> 中位数（3）：和 T1 一样右偏。

# 1.2-B 讨论要点：社区样本大多数人无症状 → 抑郁题大量 0 分 → 右偏（地板效应）；
# 后果：均值被少数高分拉高、需同时报告中位数与比例；方差小 → 皮尔逊相关被低估
