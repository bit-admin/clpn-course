# Exercise Solutions L1-3: Hand-calculating z-scores; comparing different scales (Exercises 1.3-A, 1.3-B)
source("R/_setup.R")
log_open("sol_L1-3_log.txt")
x <- c(2, 4, 1, 3, 4, 4)                       # The 6 numbers from Exercise 1.2-A
z <- (x - mean(x)) / sd(x)
cat("Mean =", mean(x), " SD =", round(sd(x), 3), "\n")
print(round(z, 2)); cat("Sum of z-scores =", round(sum(z), 10), "(should be 0)\n")
print(round(scale(x)[, 1], 2))                 # Compare with scale()
dat <- read_course_data()
zz <- scale(dat[, c("dep3_t1", "life_sat_t1")])
cat("\nParticipant 10: Raw scores\n"); print(dat[10, c("dep3_t1", "life_sat_t1")])
cat("z-scores:\n"); print(round(zz[10, ], 2))
# Under skewness, |z| cannot be directly interpreted as "how rare": inspect frequencies and percentiles directly
cat("\ndep3_t1 counts per score:\n"); print(table(dat$dep3_t1))
cat("Proportion of dep3_t1 = 0: ", round(mean(dat$dep3_t1 == 0), 3), "\n")
cat("Proportion of life_sat_t1 >= 75: ", round(mean(dat$life_sat_t1 >= 75), 3), "\n")
cat("Proportion with z >= 0.72 under normal distribution: ", round(1 - pnorm(0.72), 3), "\n")
cat("-> dep3 is severely right-skewed: score 0 is the most common response; |z| = 0.84 does not indicate 'rarity'.\n")
log_close()
