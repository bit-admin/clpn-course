# Solution L6-4: Network plot with nodeNames (Exercise 1); T1 vs. T2 cross-sectional network comparison (Exercise 2)
source("R/_setup.R")
need_output("L6-4_dep_anx_items.csv", "R/L6-4.R")   # Prerequisite output check
suppressPackageStartupMessages({ library(bootnet); library(qgraph) })
log_open("sol_L6-4_log.txt")
items16 <- read.csv(out("L6-4_dep_anx_items.csv"))      # Generated by R/L6-4.R
net <- estimateNetwork(items16, default = "EBICglasso", tuning = 0.5, corMethod = "cor_auto", verbose = FALSE)
png_open("sol_L6-4_nodenames.png", 2200, 1400)
plot(net, layout = "spring", groups = list(Depression = 1:9, Anxiety = 10:16),
     nodeNames = c(paste("Depression Item", 1:9), paste("Anxiety Item", 1:7)), legend.cex = 0.4, palette = "colorblind")
invisible(dev.off())
cat("Exercise 1: Plot saved to R/output/sol_L6-4_nodenames.png\n")
# Exercise 2: Cross-sectional networks for T1 and T2 in course data
dat <- read_course_data()
x1 <- dat[, vars_t(1)]; x2 <- dat[, vars_t(2)]; names(x1) <- names(x2) <- items
n1 <- estimateNetwork(x1, default = "EBICglasso", corMethod = "cor_auto", verbose = FALSE)
n2 <- estimateNetwork(x2, default = "EBICglasso", corMethod = "cor_auto", verbose = FALSE)
L  <- averageLayout(n1, n2); mx <- max(abs(c(n1$graph, n2$graph)))
png_open("sol_L6-4_T1_T2.png", 2400, 1100)
par(mfrow = c(1, 2))
plot(n1, layout = L, maximum = mx, groups = groups_list, title = "T1")
plot(n2, layout = L, maximum = mx, groups = groups_list, title = "T2")
invisible(dev.off())
ut <- upper.tri(n1$graph)
cat("Exercise 2: T1 edge count =", sum(n1$graph[ut] != 0), "; T2 edge count =", sum(n2$graph[ut] != 0),
    "; correlation of edge weights between the two networks =", round(cor(n1$graph[ut], n2$graph[ut]), 3), "\n")
log_close()
